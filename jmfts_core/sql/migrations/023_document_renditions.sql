-- Migration 023: derived bytes get a table, because the uploaded ones will not share theirs.
--
-- `OFFICE_SPEC.md` Part 6, `SPRINT_0_6_0.md` Block G step 32. A rendition is a PDF of the
-- source document, produced by LibreOffice at ingest so that serving a citation image is
-- pymupdf over stored bytes on any node in the fleet. The legacy conversion of Part 1 —
-- `.doc` to `.docx`, so the tier-2 readers can open it — is the same kind of artefact and
-- lands here under a different `kind`.
--
-- WHY NOT A SECOND document_blobs ROW. That table's document_id is UNIQUE and migration 009
-- says why in the DDL: "One blob per document; a second version is a new node, not a second
-- row." A rendition is not a second version of the upload, it is derived from it, so storing
-- it there would have meant dropping the constraint that asserts the upload is immutable in
-- order to hold something that is not the upload.
--
-- The lifecycles decide it. `SPRINT_0_6_0.md` Block G answers `OFFICE_SPEC.md` Part 12
-- question 1 — that question proposed renditions off by default because they "roughly double
-- blob storage for office documents", and the measurement says otherwise: of a 2988 MB
-- reference database the original bytes are 144 MB, 4.8%, so the upper bound if every stored
-- byte were an office document with a same-sized rendition is +4.8%. Renditions are therefore
-- ON, always, and the policy for them is CACHE EVICTION rather than retention: every row here
-- can be deleted and regenerated by re-running `render:pdf`, and no row in document_blobs
-- can be regenerated by anything.
--
-- READ THIS BEFORE TOUCHING THE TABLE, same as 009: a large object is NOT stored in any
-- table. The ON DELETE CASCADE below removes the row and leaves the object behind, orphaned
-- and unreachable. Deletion goes through RenditionRepository, and this table is named in
-- BlobRepository._OID_SOURCES — without that entry, find_orphaned_lobs() would classify every
-- rendition in the database as garbage and cleanup_orphaned_lobs() would destroy them.
--
-- REVERSIBILITY: DROP TABLE document_renditions, after unlinking its objects
-- (SELECT lo_unlink(lob_oid) FROM document_renditions). A 0.5.x process reading this database
-- never looks at the table and is unaffected by its presence.

BEGIN;

CREATE TABLE IF NOT EXISTS document_renditions (
    id SERIAL PRIMARY KEY,
    document_id INTEGER NOT NULL REFERENCES documents(id) ON DELETE CASCADE,
    -- 'pdf' for a rendition, 'ooxml' for a converted legacy binary. An open string, not a
    -- CHECK: the values this appliance writes are constants in the repository.
    kind VARCHAR(32) NOT NULL,
    -- UNIQUE: two rows naming one object would make deleting either destroy the other's
    -- bytes, silently. Same reasoning as document_blobs.lob_oid.
    lob_oid OID NOT NULL UNIQUE,
    mime_type TEXT NOT NULL,
    byte_size BIGINT NOT NULL,
    content_hash VARCHAR(64) NOT NULL,
    -- Which LibreOffice, as the deployment declared it (JMFTS_CONVERT_VERSION). NULLABLE:
    -- unoserver reports its own version and not the office suite's, so a deployment that did
    -- not declare one has not measured it. SPRINT_0_6_0.md 4.9.
    renderer_version VARCHAR(64),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    -- One rendition per (document, kind). A re-render REPLACES; see RenditionRepository.store.
    CONSTRAINT uq_document_renditions_document_kind UNIQUE (document_id, kind)
);

-- The lookup every read does: "does this node have a pdf rendition". The unique constraint
-- above already indexes (document_id, kind) and serves it; this one serves the subtree unlink
-- and the per-document listing, which lead with document_id alone.
CREATE INDEX IF NOT EXISTS ix_document_renditions_document
    ON document_renditions(document_id);

-- Every delta from 017 on ends with these three lines. `ON CONFLICT DO NOTHING` so a re-run
-- against a `schema.sql`-built database leaves that database's own 'schema' row standing.
INSERT INTO schema_migrations (name, applied_at, source) VALUES
    ('023_document_renditions.sql', NOW(), 'delta')
ON CONFLICT (name) DO NOTHING;

COMMIT;
