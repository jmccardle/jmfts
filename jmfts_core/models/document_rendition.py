"""DocumentRendition — a DERIVED representation of a document's bytes.

``docs/OFFICE_SPEC.md`` Part 6. A rendition is a PDF of the source document, produced once at
ingest so that serving a citation image is ``pymupdf`` over stored bytes and needs no tier-3
dependency on the query path. The conversion of a legacy ``.doc`` to ``.docx`` (Part 1's other
reason for LibreOffice) is stored here too, under a different ``kind``.

**Why a second table rather than a second ``document_blobs`` row.** That table's
``document_id`` is UNIQUE and its repository refuses a second write, and both are load-bearing
statements: "a file node holds exactly the bytes it was uploaded with; a second version is a
new node, not a second row here". A rendition is not a second version of the upload — it is
derived FROM the upload — and putting it in that table would have meant dropping the
constraint that says the upload is immutable in order to store something that is not the
upload.

The two also have opposite lifecycles, which is what settles it. ``SPRINT_0_6_0.md`` Block G
answers ``OFFICE_SPEC.md`` Part 12 question 1: renditions are on always and the policy for
them is **cache eviction, not retention** — a rendition can be deleted and regenerated by
re-running ``render:pdf``, and the original bytes cannot be regenerated by anything. A table
whose rows are all discardable is a different table from one whose rows are the only copy.

**The large object is not owned by this row**, exactly as for ``document_blobs``: ``ON DELETE
CASCADE`` removes the row and leaves the object. Deletion goes through
:class:`~jmfts_core.repositories.rendition.RenditionRepository`, and this table is named in
``BlobRepository._OID_SOURCES`` so that ``find_orphaned_lobs`` does not classify every
rendition in the database as garbage. Adding it there was part of creating this table, which
is what that constant's comment asks for.
"""

from datetime import datetime

from sqlalchemy import (
    BigInteger,
    DateTime,
    ForeignKey,
    Integer,
    String,
    Text,
    UniqueConstraint,
    func,
)
from sqlalchemy.dialects.postgresql import OID
from sqlalchemy.orm import Mapped, mapped_column

from jmfts_core.database import Base


class DocumentRendition(Base):
    """One derived representation of one document's bytes, in a Postgres large object."""

    __tablename__ = "document_renditions"

    __table_args__ = (
        # One rendition per (document, kind). A second `render:pdf` REPLACES rather than
        # appends — see `RenditionRepository.store`, which is the opposite of
        # `BlobRepository.store`'s refusal and says why there.
        UniqueConstraint("document_id", "kind", name="uq_document_renditions_document_kind"),
    )

    id: Mapped[int] = mapped_column(Integer, primary_key=True)

    document_id: Mapped[int] = mapped_column(
        Integer, ForeignKey("documents.id", ondelete="CASCADE"), nullable=False, index=True
    )

    # What this derivation IS: `pdf` for a rendition, `ooxml` for a converted legacy binary.
    # An open string rather than a CHECK, for `task_type`'s reason (INGEST_SPEC.md Part 4):
    # the values this appliance writes are constants in the repository, and an application
    # storing its own derivation is not something the schema should have to be edited for.
    kind: Mapped[str] = mapped_column(String(32), nullable=False)

    # NOT a foreign key — pg_largeobject_metadata cannot be referenced. UNIQUE for
    # `document_blobs.lob_oid`'s reason: two rows naming one object would make deleting
    # either destroy the other's bytes, silently.
    lob_oid: Mapped[int] = mapped_column(OID, nullable=False, unique=True)

    mime_type: Mapped[str] = mapped_column(Text, nullable=False)

    byte_size: Mapped[int] = mapped_column(BigInteger, nullable=False)

    # Bare sha256 hex, matching the `documents.content_hash` convention. It answers "is this
    # the same rendition I read last time" for a caller that cached one, and it is what a
    # re-render after an upgrade is compared against.
    content_hash: Mapped[str] = mapped_column(String(64), nullable=False)

    # Which converter produced it, as the deployment declared it (`JMFTS_CONVERT_VERSION`).
    # SPRINT_0_6_0.md 4.9: two LibreOffice versions paginate differently, so a rectangle
    # recovered against one is not a rectangle on the other. NULLABLE, because unoserver
    # cannot report the office suite's version and a deployment that did not declare one has
    # genuinely not measured it — see `convert.renderer_version`.
    renderer_version: Mapped[str] = mapped_column(String(64), nullable=True)

    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), nullable=False, server_default=func.now()
    )

    def __repr__(self) -> str:  # pragma: no cover - debugging aid
        return (
            f"<DocumentRendition doc={self.document_id} kind={self.kind!r} "
            f"oid={self.lob_oid} bytes={self.byte_size}>"
        )
