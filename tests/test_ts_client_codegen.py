def test_the_call_event_is_exactly_the_nine_fields_of_ic6():
    """IC-6 fixes the shape, and the runtime names it in one place.

    Pinned by reading ``CALL_EVENT_FIELDS`` out of the source rather than by executing it, so
    this holds in an environment with no JavaScript runtime. The node test below then checks
    that an event actually produced has those keys and no others.
    """
    source = (TARGET_DIR / "transport.js").read_text(encoding="utf-8")
    start = source.index("export const CALL_EVENT_FIELDS = Object.freeze([")
    body = source[start : source.index("]);", start)]
    declared = tuple(name.strip().strip('",') for name in body.splitlines()[1:] if name.strip())
    assert declared == IC6_CALL_EVENT


def test_nothing_in_the_bundle_loads_from_the_network():
    """The appliance is expected to run air-gapped.

    A page that renders blank without internet is worse than no page, so there is no CDN, no
    font host and no analytics beacon anywhere in the bundle. Checked over the whole static
    directory rather than the client alone, because the failure arrives by somebody pasting
    a ``<script src>`` into the HTML.
    """
    # A URL in prose or in a comment is documentation, and ``copyout.js`` prints one as the
    # default origin of a Python example. What must not exist is a URL the browser FETCHES:
    # a script or stylesheet source, a module import, or a CSS url().
    fetching = re.compile(
        r"""(?:src|href)\s*=\s*["']https?:|from\s+["']https?:|import\(["']https?:|url\(\s*["']?https?:""",
        re.IGNORECASE,
    )
    offenders = []
    for path in sorted(STATIC.rglob("*")):
        if not path.is_file() or path.suffix not in (".html", ".js", ".css"):
            continue
        for number, line in enumerate(path.read_text(encoding="utf-8").splitlines(), 1):
            if fetching.search(line):
                offenders.append(f"{path.relative_to(STATIC)}:{number}: {line.strip()}")
    assert not offenders, "the bundle reaches outside this origin: " + str(offenders)


def test_copy_out_cannot_print_a_credential():
    """The third property of step 23 says the token is elided, and this is what holds it.

    ``copyout.js`` names the environment variable each credential lives in and never reads
    one. Asserted structurally: the module must not touch storage or the transport's
    credential reader, because a renderer that could get the value could print it.
    """
    source = (TARGET_DIR / "copyout.js").read_text(encoding="utf-8")
    for forbidden in ("sessionStorage", "localStorage", "getCredential", "credentialFromSession"):
        assert forbidden not in source, f"copyout.js reaches for {forbidden}"


def test_the_page_keeps_the_token_in_session_storage_and_out_of_the_url():
    """Step 19's rule, which step 23 had to preserve while replacing the fetch wrapper."""
    # ``localStorage`` is NAMED in both files, in the comments that say why it is not used.
    # What must not exist is a call against it: a credential that outlives the tab.
    used = re.compile(r"(?<![.\w])(?:window\.)?localStorage\s*\.")
    page = (STATIC / "index.html").read_text(encoding="utf-8")
    assert "sessionStorage" in page
    assert not used.search(page), "the page writes to localStorage"
    transport = (TARGET_DIR / "transport.js").read_text(encoding="utf-8")
    assert 'JMFTSToken: "jmfts.token"' in transport
    assert not used.search(transport), "the transport writes to localStorage"


# ------------------------------------------------------------------- run it, if we can


NODE = shutil.which("node")
needs_node = pytest.mark.skipif(NODE is None, reason="no JavaScript runtime on PATH")

HARNESS = textwrap.dedent("""
    import assert from "node:assert/strict";
    import { JmftsClient, asCurl, asFetch, asPython } from "./index.js";

    const IC6 = %(fields)s;
    const seen = [];
    const replies = [];

    const client = new JmftsClient({
      baseUrl: "http://appliance:8100",
      getCredential: () => "SECRET-TOKEN",
      fetchImpl: async () => replies.shift(),
      now: (() => { let t = 0; return () => (t += 12); })(),
    });
    client.onCall((event) => seen.push(event));

    // --- a JSON operation ----------------------------------------------------------
    replies.push(new Response(JSON.stringify({ hits: 3 }), {
      status: 200, headers: { "content-type": "application/json" },
    }));
    const result = await client.search({ request: { query: "kittens" } });
    assert.deepEqual(result, { hits: 3 });
    assert.equal(seen.length, 1, "one call, one event");
    assert.deepEqual(Object.keys(seen[0]), IC6, "the event is exactly IC-6's nine fields");
    assert.equal(seen[0].op_id, "SearchService.search");
    assert.equal(seen[0].path, "/search");
    assert.deepEqual(seen[0].body, { query: "kittens" });
    assert.equal(seen[0].status, 200);
    assert.equal(seen[0].ms, 12);

    // --- a binary operation returns bytes, not parsed JSON --------------------------
    replies.push(new Response(new Uint8Array([137, 80, 78, 71]), {
      status: 200, headers: { "content-type": "image/png" },
    }));
    const image = await client.page_image({ document_id: 42, page: 3 });
    assert.ok(image instanceof Blob, "a binary operation resolves to bytes");
    assert.equal(new Uint8Array(await image.arrayBuffer())[0], 137);
    assert.equal(seen[1].path, "/documents/42/image");
    assert.deepEqual(seen[1].query, { page: 3 });

    // --- replay: an event is a call plus its arguments ------------------------------
    replies.push(new Response(JSON.stringify({ hits: 9 }), {
      status: 200, headers: { "content-type": "application/json" },
    }));
    const again = await client.replay(seen[0], { request: { query: "puppies" } });
    assert.deepEqual(again, { hits: 9 });
    assert.deepEqual(seen[2].body, { query: "puppies" });

    // --- copy-out, and the credential is in none of it -------------------------------
    const printed = [
      asCurl(seen[0], { baseUrl: "http://appliance:8100" }),
      asPython(seen[0], { baseUrl: "http://appliance:8100" }),
      asFetch(seen[0], { baseUrl: "http://appliance:8100" }),
    ];
    for (const text of printed) {
      assert.ok(!text.includes("SECRET-TOKEN"), "the credential must never be printed");
    }
    assert.ok(printed[0].includes('Bearer $JMFTS_API_TOKEN'), printed[0]);
    assert.ok(printed[0].includes("curl -sS -X POST"), printed[0]);
    assert.ok(printed[1].includes("client.search("), printed[1]);
    assert.ok(printed[1].includes('"query": "kittens"'), printed[1]);
    assert.ok(printed[2].includes("await fetch("), printed[2]);
    assert.ok(asCurl(seen[1]).includes("-o out.png"), "a binary call saves its bytes");

    // --- an argument the operation does not declare is refused ----------------------
    await assert.rejects(
      client.search({ request: { query: "x" }, limitt: 5 }),
      /no parameter "limitt"/,
    );

    // --- a 4xx throws, and the event still records it -------------------------------
    replies.push(new Response(JSON.stringify({ detail: "nope" }), {
      status: 404, headers: { "content-type": "application/json" },
    }));
    await assert.rejects(client.search({ request: { query: "x" } }), /HTTP 404: nope/);
    assert.equal(seen.at(-1).status, 404);
    assert.deepEqual(seen.at(-1).response, { detail: "nope" });

    console.log("ok");
    """)


@needs_node
def test_the_generated_client_really_emits_one_event_per_call(tmp_path):
    """Execute the thing, against a synthetic surface that carries a binary operation.

    Everything above reads text. This runs it: one call, one event, nine fields; a binary
    operation hands back bytes; an event replays with an edited argument; and none of the
    three copy-out renderings contains the credential the client was given.
    """
    for name, text in generate(_synthetic()).items():
        (tmp_path / name).write_text(text, encoding="utf-8")
    for name in RUNTIME_FILES:
        shutil.copyfile(TARGET_DIR / name, tmp_path / name)
    harness = tmp_path / "harness.mjs"
    harness.write_text(HARNESS % {"fields": json.dumps(list(IC6_CALL_EVENT))}, encoding="utf-8")

    done = subprocess.run([NODE, str(harness)], capture_output=True, text=True, cwd=tmp_path)
    assert done.returncode == 0, done.stderr or done.stdout
    assert done.stdout.strip().endswith("ok")


#: Two real calls, printed as Python, so the next test can bind them against the real client.
#: They are chosen to cover the two argument kinds a printed call can get wrong: a JSON body
#: beside a query parameter, and a path parameter whose value needs encoding on the wire and
#: must NOT be encoded in the Python source.
COPY_OUT_HARNESS = textwrap.dedent("""
    import { JmftsClient, asPython } from "%(client)s/index.js";

    const seen = [];
    const client = new JmftsClient({
      baseUrl: "http://appliance:8100",
      getCredential: () => "SECRET-TOKEN",
      fetchImpl: async () =>
        new Response("{}", { status: 200, headers: { "content-type": "application/json" } }),
    });
    client.onCall((event) => seen.push(event));

    await client.hybrid_search({ request: { query: "late interaction", limit: 5 }, rerank: true });
    await client.get_presentation({ usetype: "wiki:arxiv" });

    const out = {};
    for (const event of seen) {
      out[event.op_id] = asPython(event, { baseUrl: "http://appliance:8100" });
    }
    console.log(JSON.stringify(out));
    """)


@needs_node
def test_copy_out_prints_python_the_real_client_would_accept(tmp_path):
    """Property 3 of step 23, checked end to end rather than by eye.

    The printed call is parsed as Python and its keyword arguments are BOUND against the
    signature ``_verbs.py`` actually declares. That is the difference between a worked example
    and a worked example that runs: a renamed parameter, or an argument printed positionally
    where the verb wants a keyword, fails here instead of in somebody's terminal.

    It also holds the encoding boundary. ``wiki:arxiv`` goes on the wire as ``wiki%3Aarxiv``
    and must appear in the Python source as the value, not as the escape.
    """
    import ast
    import inspect

    from jmfts_client.remote import RemoteJmftsClient

    harness = tmp_path / "copyout.mjs"
    harness.write_text(COPY_OUT_HARNESS % {"client": TARGET_DIR.as_uri()}, encoding="utf-8")
    done = subprocess.run([NODE, str(harness)], capture_output=True, text=True, cwd=tmp_path)
    assert done.returncode == 0, done.stderr or done.stdout
    printed = json.loads(done.stdout)

    assert set(printed) == {
        "SearchService.hybrid_search",
        "UsetypePresentationService.get_presentation",
    }
    assert "SECRET-TOKEN" not in done.stdout

    for op_id, source in printed.items():
        tree = ast.parse(source)  # a syntax error here is a printed example that does not run
        calls = [
            node
            for node in ast.walk(tree)
            if isinstance(node, ast.Call)
            and isinstance(node.func, ast.Attribute)
            and isinstance(node.func.value, ast.Name)
            and node.func.value.id == "client"
        ]
        assert len(calls) == 1, f"{op_id}: expected one client call in\n{source}"
        (call,) = calls
        verb = getattr(RemoteJmftsClient, call.func.attr)
        assert call.func.attr == op_id.split(".")[-1]
        # `self` is bound on an instance, so drop it before binding the printed keywords.
        signature = inspect.signature(verb).replace(
            parameters=list(inspect.signature(verb).parameters.values())[1:]
        )
        signature.bind(**{keyword.arg: None for keyword in call.keywords})
        assert not call.args, f"{op_id} printed a positional argument; the verbs take keywords"

    presentation = printed["UsetypePresentationService.get_presentation"]
    assert 'usetype="wiki:arxiv"' in presentation
    assert "%3A" not in presentation


