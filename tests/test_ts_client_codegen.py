#: Two probes: one that must type-check and one that must not. The second is what stops the
#: first being vacuous — a declaration file too loose to reject anything type-checks
#: everything. Neither names a response field, so a contract renaming one does not fail this.
TYPE_PROBE = """
import type { JmftsClient } from "./verbs.d.ts";
import type { CallEvent } from "./transport.d.ts";
import type { SearchResponse, CapabilitiesResponse } from "./verbs.d.ts";

declare const client: JmftsClient;

export async function good(): Promise<string> {
  const hits: SearchResponse = await client.hybrid_search({
    request: { query: "late interaction" },
    rerank: true,
  });
  const caps: CapabilitiesResponse = await client.capabilities({ corpus: true });
  await client.get_presentation({ usetype: "markdown" });
  return `${hits} ${caps}`;
}

export function widen(event: CallEvent): string {
  return `${event.op_id} ${event.status} ${event.ms}`;
}
"""

BAD_TYPE_PROBE = """
import type { JmftsClient } from "./verbs.d.ts";

declare const client: JmftsClient;

export async function bad(): Promise<void> {
  await client.hybrid_search({ request: { query: 17 } });
  await client.capabilities({ corpuss: true });
}
"""


@pytest.mark.skipif(DENO is None, reason="no TypeScript checker on PATH")
def test_the_generated_declarations_type_check(tmp_path):
    """The 3900 generated declaration lines are the part nothing else looks at.

    ``verbs.d.ts`` is what a TypeScript view checks against, and a declaration file with a
    syntax error or an unresolvable reference fails silently — the checker falls back to
    ``any`` and everything passes. This runs a checker over the real bundle.

    Deno rather than ``tsc`` because Deno type-checks TypeScript without a compiler install
    or a ``tsconfig.json``, and because it is what is here. The ``@ts-self-types`` pragma at
    the top of each ``.js`` is what points it at the declarations; ``tsc`` finds them from the
    filename and does not need it.
    """
    # Copied out rather than probed in place: TARGET_DIR is checked file-for-file by
    # ``test_the_client_directory_holds_nothing_else``, and a scratch file left there by a
    # crashed run would fail a different test with a confusing message.
    work = tmp_path / "client"
    shutil.copytree(TARGET_DIR, work)
    (work / "probe.ts").write_text(TYPE_PROBE, encoding="utf-8")
    (work / "negative.ts").write_text(BAD_TYPE_PROBE, encoding="utf-8")

    good = subprocess.run(
        [DENO, "check", "--no-lock", str(work / "probe.ts")], capture_output=True, text=True
    )
    assert good.returncode == 0, good.stderr or good.stdout
    bad = subprocess.run(
        [DENO, "check", "--no-lock", str(work / "negative.ts")], capture_output=True, text=True
    )
    assert bad.returncode != 0, (
        "the declarations accepted a call with a wrong argument type and an unknown "
        "parameter, so they are too loose to be checking anything"
    )
