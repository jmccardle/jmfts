"""The browser client must match the surface it was generated from.

``docs/SPRINT_0_6_0.md`` Block F step 23, IC-6. The same seal ``tests/test_client_codegen.py``
puts on ``_verbs.py`` and ``tests/test_reference_docs.py`` puts on ``docs/reference/``, for
the same reason: a generated artefact checked into the tree is worth exactly what its
staleness check is worth, and a front end generated against a route table that has since
moved renders controls for operations that are not there.

These need no database and no browser. They read the tree, build the app's OpenAPI document
in memory, and — where a JavaScript runtime is available — execute the generated module
against a stubbed ``fetch`` to check that a call really does emit one event and that a binary
operation really does hand back bytes.
"""

