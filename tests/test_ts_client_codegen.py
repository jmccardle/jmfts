def test_the_operation_table_covers_the_whole_mounted_surface():
    """One entry per mounted route — the front end cannot be a subset of the appliance.

    This is the check that makes the generator worth having. ``_verbs.py`` covers the 108
    ``@expose``'d operations; the document covers all 115, because seven routes are written
    by hand in ``rest/main.py`` and the browser needs them (``/health`` most of all: it is
    how the page tells "no credential" from "nothing is running").
    """
    table = operation_table()
    mounted = {route.name for route in iter_mounted_api_routes(app)}
    assert (
        set(table) == mounted
    ), f"missing: {sorted(mounted - set(table))}, extra: {sorted(set(table) - mounted)}"


def test_every_exposed_operation_names_its_python_verb():
    """An operation id maps to a ``_verbs.py`` method name — property 3 of step 23.

    That mapping is what copy-out rests on: the event prints as a ``RemoteJmftsClient`` call
    because the table says which method it is. A wrong name here is a worked example that
    does not run.
    """
    table = operation_table()
    expected = {spec.name: spec.func.__name__ for spec in REGISTRY}
    actual = {op_id: row["python_verb"] for op_id, row in table.items() if row["python_verb"]}
    assert actual == expected


def test_the_routes_without_a_python_verb_are_the_seven_hand_written_ones():
    """A route that gained an ``@expose`` must leave this list, and one that lost it join."""
    table = operation_table()
    without = {op_id for op_id, row in table.items() if not row["python_verb"]}
    assert without == ROUTES_WITHOUT_A_PYTHON_VERB, (
        f"gained: {sorted(without - ROUTES_WITHOUT_A_PYTHON_VERB)}, "
        f"lost: {sorted(ROUTES_WITHOUT_A_PYTHON_VERB - without)}"
    )


def test_client_method_names_are_unique():
    """The client is one flat namespace, exactly as ``_verbs.py`` is."""
    members = [op_id.split(".")[-1] for op_id in operation_table()]
    duplicates = sorted({name for name in members if members.count(name) > 1})
    assert not duplicates, f"two operations want one client method name: {duplicates}"


def test_every_operation_has_a_client_method():
    source = (TARGET_DIR / "verbs.js").read_text(encoding="utf-8")
