def _synthetic(**overrides) -> dict:
    """A minimal document with one JSON operation and one binary one.

    ``wt/bytes`` is adding ``/documents/{id}/blob``, ``/image`` and ``/region`` in parallel
    and they are not in this tree yet, so the branch that returns bytes instead of parsing
    JSON is covered here rather than against a route that does not exist. The binary response
    is the literal shape ``rest/wiring.py::_BINARY_SCHEMA`` writes.
    """
    image = {
        "tags": ["documents"],
        "summary": "One rendered page",
        "operationId": "DocumentService_page_image_documents__document_id__image_get",
        "security": [{"JMFTSToken": []}],
        "parameters": [
            {
                "name": "document_id",
                "in": "path",
                "required": True,
                "schema": {"type": "integer"},
            },
            {"name": "page", "in": "query", "required": False, "schema": {"type": "integer"}},
        ],
        "responses": {
            "200": {
                "description": "Successful Response",
                "content": {"image/png": {"schema": {"type": "string", "format": "binary"}}},
            }
        },
        ROUTE_EXTENSION: {
            "name": "DocumentService.page_image",
            "path_template": "/documents/{document_id}/image",
            "body_param": None,
            "python_verb": "page_image",
        },
    }
    image.update(overrides)
    return {
        "openapi": "3.1.0",
        "paths": {
            "/documents/{document_id}/image": {"get": image},
            "/search": {
                "post": {
                    "tags": ["search"],
                    "summary": "Search",
                    "operationId": "SearchService_search_search_post",
                    "security": [{"JMFTSToken": []}],
                    "requestBody": {
                        "required": True,
                        "content": {
                            "application/json": {
                                "schema": {"$ref": "#/components/schemas/SearchRequest"}
                            }
                        },
                    },
                    "responses": {
                        "200": {
                            "description": "OK",
                            "content": {"application/json": {"schema": {"type": "object"}}},
                        }
                    },
                    ROUTE_EXTENSION: {
                        "name": "SearchService.search",
                        "path_template": "/search",
                        "body_param": "request",
                        "python_verb": "search",
                    },
                }
            },
        },
        "components": {
            "securitySchemes": {"JMFTSToken": {"type": "http", "scheme": "bearer"}},
            "schemas": {
                "SearchRequest": {
                    "type": "object",
                    "properties": {"query": {"type": "string"}},
                    "required": ["query"],
                }
            },
        },
    }


def test_a_binary_response_is_read_as_bytes_and_a_json_one_is_not():
    table = operation_table(generate(_synthetic())["operations.js"])
    image = table["DocumentService.page_image"]
    assert image["binary"] is True
    assert image["response_media_type"] == "image/png"
    assert table["SearchService.search"]["binary"] is False


